"""Write static/timezones.js: every zone in tzdata's zone.tab with its POSIX rule.

The board runs on a POSIX TZ string, the browser names its zone the IANA way, and
the settings page needs both to offer a dropdown. The rule is the footer line that
TZif v2+ files carry, so it is exactly what glibc and newlib would use.

    pip download tzdata --no-deps -d tz && unzip tz/*.whl -d tz
    PYTHONPATH=tz python esp32/timezones.py
"""

import json
from importlib import resources
from pathlib import Path

import tzdata

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "static" / "timezones.js"
ZONEINFO = resources.files("tzdata") / "zoneinfo"


def rule(name):
    data = (ZONEINFO / name).read_bytes()
    footer = data.rstrip(b"\n").rsplit(b"\n", 1)[1].decode("ascii")
    if not footer:
        raise SystemExit(f"{name} has no POSIX footer")
    return footer


def listed():
    names = ["UTC"]
    for line in (ZONEINFO / "zone.tab").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            names.append(line.split("\t")[2])
    return sorted(set(names))


def links():
    target = {}
    for line in (ZONEINFO / "tzdata.zi").read_text(encoding="utf-8").splitlines():
        if line.startswith("L "):
            _, to, name = line.split()
            target[name] = to
    return target


def canonical(name, target):
    while name in target:
        name = target[name]
    return name


def main():
    zones = {name: rule(name) for name in listed()}
    target = links()
    by_canonical = {}
    for name in zones:
        by_canonical.setdefault(canonical(name, target), name)

    # Browsers still report old names such as Asia/Calcutta, so those point at the
    # listed zone they mean.
    aliases = {}
    every = resources.files("tzdata").joinpath("zones").read_text(encoding="utf-8").split()
    for name in every:
        if name in zones:
            continue
        listed_as = by_canonical.get(canonical(name, target))
        if listed_as:
            aliases[name] = listed_as

    def block(table):
        return ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in sorted(table.items()))

    OUT.write_text(
        f"// Generated by esp32/timezones.py from tzdata {tzdata.IANA_VERSION}. Do not edit.\n"
        f"window.TIMEZONES = {{\n{block(zones)},\n}};\n"
        f"window.TIMEZONE_ALIASES = {{\n{block(aliases)},\n}};\n",
        encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(zones)} zones, {len(aliases)} aliases")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Write main/selftest_vectors.h from the Python node's own functions.

The firmware's self-test feeds these inputs to its C port and compares the
results, so the two can only drift apart by someone forgetting to rerun this.
Run it from anywhere: python esp32/node/tools/selftest_vectors.py
"""

import os
import struct
import sys
import time
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parents[1] / "main" / "selftest_vectors.h"

# lywsd02.py imports bleak at the top; none of the code used here touches it.
bleak = types.ModuleType("bleak")
bleak.BleakClient = bleak.BleakScanner = object
sys.modules["bleak"] = bleak
sys.path.insert(0, str(ROOT))
import cluster  # noqa: E402
import lywsd02  # noqa: E402

real_localtime = time.localtime


def with_offset(offset):
    """localtime() as seen from a zone `offset` seconds east of UTC."""
    def localtime(seconds=None):
        base = real_localtime(seconds)
        return types.SimpleNamespace(tm_gmtoff=offset, **{
            name: getattr(base, name) for name in
            ("tm_year", "tm_mon", "tm_mday", "tm_hour", "tm_min", "tm_sec",
             "tm_wday", "tm_yday", "tm_isdst")})
    return localtime


# (POSIX TZ the board is given, offset east of UTC that zone has at `now`, now)
ZONES = [
    ("CST-8", 8 * 3600, 1762400000.25),
    ("UTC0", 0, 1762400000.0),
    ("<-0230>2:30", -9000, 1762400000.9),
    ("<-0330>3:30", -12600, 1762412345.5),
    ("<+0530>-5:30", 19800, 1762400000.0),
    ("<+0545>-5:45", 20700, 1762400017.0),
    ("<-10>10", -36000, 1762400000.0),
    ("<+1345>-13:45", 49500, 1762400000.0),
    ("CET-1CEST,M3.5.0,M10.5.0/3", 7200, 1751328000.0),
    ("CET-1CEST,M3.5.0,M10.5.0/3", 3600, 1762400000.0),
    # Switch hours outside 0-24 (RFC 8536), from static/timezones.js; each instant
    # falls between the right switch and the one a clamped hour would give.
    ("IST-2IDT,M3.4.4/26,M10.5.0", 7200, 1774567800.0),
    ("IST-2IDT,M3.4.4/26,M10.5.0", 10800, 1774571400.0),
    ("<-02>2<-01>,M3.5.0/-1,M10.5.0/0", -3600, 1774747800.0),
    ("<-02>2<-01>,M3.5.0/-1,M10.5.0/0", -7200, 1774744200.0),
]

# What a clock may hand back from ccb7; read at each zone's own `now`.
CLOCK_READS = ["00a00b6908", "1d9c0b6908", "10a40b69fd0000", "00000000000000"]

ENV = ["c40924", "4cff5a", "1e0a37a40b", "e803006400", "01", "", "ffff00ffff"]


def adv(name=None, short=None, uuids128=(), fe95=None, other=None):
    data = b"\x02\x01\x06"
    if short is not None:
        raw = short.encode()
        data += bytes([len(raw) + 1, 0x08]) + raw
    if name is not None:
        raw = name.encode()
        data += bytes([len(raw) + 1, 0x09]) + raw
    for uuid in uuids128:
        raw = bytes.fromhex(uuid.replace("-", ""))[::-1]
        data += bytes([len(raw) + 1, 0x07]) + raw
    if fe95 is not None:
        raw = b"\x95\xfe" + fe95
        data += bytes([len(raw) + 1, 0x16]) + raw
    if other is not None:
        data += other
    return data


class Device:
    def __init__(self, name):
        self.name = name


class Adv:
    def __init__(self, name, uuids, service_data):
        self.local_name = name
        self.service_uuids = uuids
        self.service_data = service_data


ADVERTS = [
    ("name only", dict(name="LYWSD02")),
    ("lower-case name", dict(name="lywsd02mmc")),
    ("shortened name", dict(short="LYWSD02")),
    ("service uuid", dict(uuids128=[lywsd02.SERVICE_UUID])),
    ("MMC pid, no name", dict(fe95=bytes.fromhex("3059422501a4c138"))),
    ("LYWSD02 pid", dict(fe95=bytes.fromhex("30585b0401"))),
    ("other pid", dict(name="MJ_HT_V1", fe95=bytes.fromhex("30588a0401"))),
    ("short fe95", dict(fe95=bytes.fromhex("3058"))),
    ("someone else", dict(name="Buds", uuids128=["0000fd6f-0000-1000-8000-00805f9b34fb"])),
    ("nothing", dict()),
    ("broken length", dict(name="X", other=b"\x09\x16\x95\xfe")),
]


def semantic(fields):
    name = fields.get("name") or fields.get("short")
    uuids = list(fields.get("uuids128", []))
    data = {}
    if fields.get("fe95") is not None:
        data[lywsd02.XIAOMI_SERVICE_DATA] = fields["fe95"]
    return Device(None), Adv(name, uuids, data)


def c_bytes(raw):
    return "{" + ", ".join(f"0x{b:02x}" for b in raw) + "}" if raw else "{0}"


def c_str(text):
    return "NULL" if text is None else '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_num(value):
    return "NAN" if value is None else repr(float(value))


def main():
    lines = ["// Generated by tools/selftest_vectors.py from lywsd02.py and cluster.py.",
             "// Do not edit; rerun the script instead.", "#pragma once", ""]

    lines.append("static const struct { const char *tz; int offset; double now; "
                 "uint8_t encoded[5]; } TIME_VECTORS[] = {")
    for tz, offset, now in ZONES:
        lywsd02.time.localtime = with_offset(offset)
        encoded = lywsd02.encode_time(now)
        lines.append(f"    {{{c_str(tz)}, {offset}, {now!r}, {c_bytes(encoded)}}},")
    lines.append("};")

    lines.append("static const struct { const char *tz; int offset; double now; uint8_t raw[7]; "
                 "int length; double shown; int timezone; double drift; } CLOCK_VECTORS[] = {")
    for tz, offset, now in ZONES:
        lywsd02.time.localtime = with_offset(offset)
        for raw_hex in CLOCK_READS:
            raw = bytes.fromhex(raw_hex)
            stamp, timezone = lywsd02.decode_time(raw)
            shown = lywsd02.shown_time(stamp, timezone, now)
            lines.append(f"    {{{c_str(tz)}, {offset}, {now!r}, {c_bytes(raw)}, {len(raw)}, "
                         f"{float(shown)!r}, {timezone}, {float(shown - int(now))!r}}},")
    lines.append("};")
    lywsd02.time.localtime = real_localtime

    lines.append("static const struct { uint8_t data[8]; int length; bool ok; double temperature; "
                 "int humidity; double voltage; } ENV_VECTORS[] = {")
    for raw_hex in ENV:
        raw = bytes.fromhex(raw_hex)
        report = lywsd02.decode_env(raw)
        lines.append(f"    {{{c_bytes(raw)}, {len(raw)}, {'true' if report else 'false'}, "
                     f"{c_num(report.get('temperature'))}, {report.get('humidity', -1)}, "
                     f"{c_num(report.get('voltage'))}}},")
    lines.append("};")

    lines.append("static const struct { const char *what; uint8_t data[31]; int length; "
                 "const char *name; int product_id; bool clock; } ADV_VECTORS[] = {")
    for what, fields in ADVERTS:
        raw = adv(**fields)
        assert len(raw) <= 31, what
        device, record = semantic(fields)
        pid = lywsd02.product_id(record)
        name = record.local_name
        lines.append(f"    {{{c_str(what)}, {c_bytes(raw)}, {len(raw)}, {c_str(name)}, "
                     f"{-1 if pid is None else pid}, "
                     f"{'true' if lywsd02.looks_like_clock(device, record) else 'false'}}},")
    lines.append("};")

    lines.append("static const struct { int rssi; int bucket; } BUCKET_VECTORS[] = {")
    for rssi in (-30, -45, -57, -60, -63, -66, -69, -75, -81, -87, -93, -99, -100, 0):
        lines.append(f"    {{{rssi}, {round(rssi / cluster.BUCKET)}}},")
    lines.append("};")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
